std::string build_print_document(std::string_view title, const std::vector<std::pair<Contract, Tenant>> &items,
                                  const OrganizationSettings &org) {
    std::ostringstream out;
    out << R"(<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>)"
        << html_escape(std::string(title)) << R"(</title>
<style>)"
        << layout::kPrintCss << R"html(</style>
</head>
<body>
<div class="toolbar">
<a href="/contracts">Назад к списку</a>
<a class="print" href="javascript:window.print()">Печать</a>
</div>)html";

    if (items.empty()) {
        out << R"(<div class="print-page"><div class="doc-p">Нет договоров для печати.</div></div>)";
    } else {
        for (const auto &[contract, tenant] : items) {
            out << build_contract_print_fragment(contract, tenant, org);
        }
    }

    out << R"(</body>
</html>)";
    return out.str();
}

